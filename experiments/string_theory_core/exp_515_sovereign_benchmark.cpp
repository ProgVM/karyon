#include <iostream>
#include <vector>
#include <cmath>
#include <chrono>
#include <algorithm>
#include "experiments/string_theory_core/sovereign_string_organism.hpp"

using namespace karyon;

// 1. Regime B: Long-Horizon Inverted Pendulum Balancing with Sufficient Time to Learn
void run_sovereign_pendulum(SovereignStringOrganism& organism, size_t steps = 30000) {
    std::cout << ">>> Running Sovereign String Organism Regime B: Inverted Pendulum (steps=" << steps << ")...\n";
    std::cout << ">>> Giving the system sufficient time and self-plasticity to settle into ideal equilibrium...\n";
    const size_t S = 256;
    std::vector<float> curr_s(S, 0.0f);
    std::vector<float> goal_s(S, 0.0f);

    float theta = 0.15f;
    float omega = 0.0f;
    const float dt = 0.02f;
    const float g = 9.81f;
    const float L = 1.0f;
    size_t balanced_ticks = 0;
    size_t recent_balanced_ticks = 0;

    auto encode_state = [](std::vector<float>& fb, float th, float om) {
        std::fill(fb.begin(), fb.end(), 0.0f);
        int gx = std::clamp(static_cast<int>((th / 3.14159f + 1.0f) * 7.5f), 0, 15);
        int gy = std::clamp(static_cast<int>((om / 10.0f + 1.0f) * 7.5f), 0, 15);
        fb[gy * 16 + gx] = 1.0f;
    };

    encode_state(goal_s, 0.0f, 0.0f);

    auto t0 = std::chrono::high_resolution_clock::now();

    for (size_t t = 0; t < steps; ++t) {
        encode_state(curr_s, theta, omega);

        bool is_upright = (std::abs(theta) < 0.35f);
        if (is_upright) {
            balanced_ticks++;
            recent_balanced_ticks++;
        }

        if (std::abs(theta) > 1.8f) {
            theta = (t % 2 == 0 ? 0.2f : -0.2f);
            omega = 0.0f;
        }

        // Homeostatic valence: High reward when perfectly balanced, penalty when falling
        float valence = is_upright ? (1.0f - std::abs(theta)) : -1.0f;

        auto state = organism.perceive_and_act(curr_s, goal_s, valence);

        // Effective torque generated by string stress tensor
        float torque = 18.0f * (state.motor_efferent_actions[0] - state.motor_efferent_actions[1]);
        float alpha = (g / L) * std::sin(theta) - torque - 0.2f * omega;
        omega += dt * alpha;
        theta += dt * omega;

        if ((t + 1) % 5000 == 0 || t == steps - 1) {
            size_t window_size = 5000;
            float recent_pct = static_cast<float>(recent_balanced_ticks * 100) / static_cast<float>(window_size);
            recent_balanced_ticks = 0;

            std::cout << "  Step " << (t + 1) << "/" << steps 
                      << " | Theta: " << theta 
                      << " | Upright (Cumulative): " << (balanced_ticks * 100 / (t + 1)) << "%"
                      << " | Upright (Last 5k Window): " << recent_pct << "%"
                      << " | Avg Tension: " << state.avg_local_tension
                      << " | Net Torque: " << state.net_physical_torque
                      << " | Plasticity Delta: " << state.self_plasticity_rate
                      << " | FE: " << state.free_energy << "\n";
        }
    }

    auto t1 = std::chrono::high_resolution_clock::now();
    double elapsed = std::chrono::duration<double>(t1 - t0).count();

    std::cout << ">>> Pendulum Finished! Overall Upright: " 
              << (balanced_ticks * 100 / steps) << "% (" << balanced_ticks << "/" << steps << ")"
              << " | Speed: " << (steps / elapsed) << " steps/s\n\n";
}

int main() {
    std::cout << "========================================================================\n";
    std::cout << "=== EXP-515: SOVEREIGN STRING CONTINUUM SELF-CONTROL BENCHMARK =======\n";
    std::cout << "=== Validating: Full Self-Control -> 100% Ideal Equilibrium ===========\n";
    std::cout << "========================================================================\n\n";

    SovereignStringConfig cfg;
    cfg.sensory_dim = 256;
    cfg.action_dim = 4;
    cfg.num_string_modes = 48;
    cfg.grid_nx = 4;
    cfg.grid_ny = 6;
    cfg.relaxation_substeps = 8;
    cfg.base_dt = 0.04f;
    cfg.plasticity_learning_rate = 0.08f;

    SovereignStringOrganism karyon_sovereign(cfg);

    run_sovereign_pendulum(karyon_sovereign, 30000);

    return 0;
}
